// ----- tiny helpers used by every page -----
const LANG_STORAGE_KEY = "mediai_lang"; // the ONLY thing remembered by default: your language choice
let currentLang = "en";

function t(key) {
  const entry = I18N[key];
  if (!entry) return key; // a missing key shows its own name, which makes mistakes easy to spot
  const index = LANGS.findIndex((l) => l.code === currentLang);
  return entry[index] || entry[0];
}

function loadSavedLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && LANGS.some((l) => l.code === saved)) currentLang = saved;
  } catch (e) { /* storage may be blocked; English is fine */ }
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.documentElement.lang = currentLang;
}
